#!/usr/bin/env node
/**
 * Wallpaper prebuild — scan src/client/wallpapers/, downscale to 1920px JPEG
 * via macOS `sips`, base64-encode, emit src/client/bg-images.generated.ts
 * so wallpapers can be picked at runtime without re-running a manual encode.
 *
 * macOS only (sips). To add a wallpaper: drop the image into wallpapers/
 * and run `npm run bundle` (which calls this script first).
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs'
import { join, dirname, basename, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const wallpapersDir = join(root, 'src', 'client', 'wallpapers')
const buildDir = join(root, 'src', 'client', '.wallpapers-build')
const outFile = join(root, 'src', 'client', 'bg-images.generated.ts')

// id (filename without ext) -> { name, theme }
const META = {
  'porsche-718': { name: 'Porsche 718', theme: 'light' },
  'yu7-3':       { name: 'Yu7 · 公路',   theme: 'light' },
  'yu7':         { name: 'Yu7 · 公路',   theme: 'light' },
  'yu7-gt':      { name: 'Yu7 GT · 日落', theme: 'light' },
  'mcan-s':      { name: 'Macan S',      theme: 'dark'  },
  'su7-1':       { name: 'Su7 · 蓝色',   theme: 'dark'  },
  'su7':         { name: 'Su7 · 蓝色',   theme: 'dark'  },
}

mkdirSync(buildDir, { recursive: true })

const supported = new Set(['.jpg', '.jpeg', '.png'])
const entries = readdirSync(wallpapersDir)
  .filter(f => supported.has(extname(f).toLowerCase()))
  .filter(f => statSync(join(wallpapersDir, f)).isFile())
  .sort()

if (entries.length === 0) {
  console.error('[wallpapers] no images found in src/client/wallpapers/')
  process.exit(1)
}

const wallpapers = []
for (const f of entries) {
  const id = basename(f, extname(f))
  const meta = META[id] ?? { name: id, theme: 'light' }
  const out = join(buildDir, `${id}.jpg`)

  // sips: -Z keeps aspect, max edge 1920; output as jpeg @ normal quality.
  // Output format is decided by the --out extension.
  execFileSync('sips', [
    '-Z', '1920',
    '-s', 'format', 'jpeg',
    '-s', 'formatOptions', 'normal',
    join(wallpapersDir, f),
    '--out', out,
  ], { stdio: ['ignore', 'pipe', 'pipe'] })

  const buf = readFileSync(out)
  const dataUrl = `data:image/jpeg;base64,${buf.toString('base64')}`
  wallpapers.push({ id, name: meta.name, theme: meta.theme, dataUrl, bytes: buf.length })
  console.log(`[wallpapers] ${id} (${meta.theme}) -> ${(buf.length / 1024).toFixed(0)} KB`)
}

const totalBytes = wallpapers.reduce((s, w) => s + w.bytes, 0)
console.log(`[wallpapers] ${wallpapers.length} wallpapers, total ${(totalBytes / 1024).toFixed(0)} KB`)

const header = `/**
 * AUTO-GENERATED by scripts/build-wallpapers.mjs — do not edit.
 * Drop images into src/client/wallpapers/ and run \`npm run bundle\`.
 */
export interface Wallpaper {
  id: string
  name: string
  theme: 'light' | 'dark'
  dataUrl: string
}
`
const body = 'export const WALLPAPERS: Wallpaper[] = [\n'
  + wallpapers.map(w =>
      `  { id: ${JSON.stringify(w.id)}, name: ${JSON.stringify(w.name)}, theme: ${JSON.stringify(w.theme)}, dataUrl: ${JSON.stringify(w.dataUrl)} },`
    ).join('\n')
  + '\n]\n'

writeFileSync(outFile, header + body)
console.log(`[wallpapers] wrote ${outFile}`)
